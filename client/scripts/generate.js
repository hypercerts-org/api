// Generates src/ for @hypercerts-org/api from the Lexicons declared in
// api/manifest.json, in lex's own layout: the package exports lex's NSID
// namespace tree (app, com, org, pub), as in the @atproto/lex documentation.
// Modules for the API's own Lexicons (api/lexicons/) are generated here;
// everything else in the tree (records and their definitions) points at
// @hypercerts-org/lexicon/records, so no record code is copied. Run with
// --check to fail when the committed output is stale.
import { execFileSync } from "node:child_process";
import { existsSync } from "node:fs";
import { mkdir, mkdtemp, readdir, readFile, rm, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const clientRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const apiRoot = path.resolve(clientRoot, "../api");
const lexEntry = path.join(clientRoot, "node_modules/@atproto/lex/bin/lex");
const recordsSpecifier = "@hypercerts-org/lexicon/records";
const header = "/*\n * THIS FILE WAS GENERATED BY scripts/generate.js. DO NOT EDIT.\n */\n";

/** @param {string} a @param {string} b */
const byCodeUnit = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

/** The installed @hypercerts-org/lexicon: its root directory and version. */
async function lexiconPackage() {
  const require = createRequire(path.join(clientRoot, "package.json"));
  const packageFile = require.resolve("@hypercerts-org/lexicon/package.json");
  const { version } = JSON.parse(await readFile(packageFile, "utf8"));
  return { root: path.dirname(packageFile), version: /** @type {string} */ (version) };
}

/**
 * The Lexicons in api/manifest.json validationLexicons: local ones from
 * api/lexicons/, record Lexicons from the installed @hypercerts-org/lexicon.
 * @param {string} lexiconRoot
 * @returns {Promise<Array<{ id: string; local: boolean; lexicon: unknown }>>}
 */
async function manifestLexicons(lexiconRoot) {
  const manifest = JSON.parse(await readFile(path.join(apiRoot, "manifest.json"), "utf8"));
  return Promise.all(
    manifest.validationLexicons.map(async (/** @type {any} */ source) => {
      const file = source.path
        ? path.join(apiRoot, source.path)
        : path.join(lexiconRoot, source.packagePath);
      const lexicon = JSON.parse(await readFile(file, "utf8"));
      if (lexicon.id !== source.id) {
        throw new Error(
          `api/manifest.json declares ${source.id}, but its source contains ${lexicon.id}`,
        );
      }
      return { id: source.id, local: Boolean(source.path), lexicon };
    }),
  );
}

/** @param {string} id */
const lexiconPath = (id) => id.replaceAll(".", "/");

/** @param {string} dir @returns {Promise<string[]>} paths relative to dir, POSIX separators */
async function listFiles(dir) {
  const entries = await readdir(dir, { recursive: true, withFileTypes: true }).catch(() => []);
  return entries
    .filter((entry) => entry.isFile() && !entry.name.startsWith("."))
    .map((entry) =>
      path.relative(dir, path.join(entry.parentPath, entry.name)).split(path.sep).join("/"),
    )
    .sort(byCodeUnit);
}

/**
 * The generated files this package keeps: the modules of the API's own
 * Lexicons, the namespace modules on the path to them, and the index.
 * @param {string[]} files
 * @param {string[]} localIds
 */
function keptFiles(files, localIds) {
  const localPaths = localIds.map(lexiconPath);
  const own = new Set(localPaths.flatMap((p) => [`${p}.ts`, `${p}.defs.ts`]));
  return new Set(
    files.filter((file) => {
      if (file === "index.ts" || own.has(file)) return true;
      if (file.endsWith(".defs.ts")) return false;
      const namespace = file.slice(0, -".ts".length);
      return localPaths.some((p) => p.startsWith(`${namespace}/`));
    }),
  );
}

/**
 * Keeps only this package's modules and points every import or re-export of
 * another module at @hypercerts-org/lexicon/records.
 * @param {string} lexiconsDir generated output
 * @param {string[]} localIds
 * @param {string} lexiconRoot installed @hypercerts-org/lexicon
 */
async function linkRecords(lexiconsDir, localIds, lexiconRoot) {
  const files = await listFiles(lexiconsDir);
  const keep = keptFiles(files, localIds);
  await Promise.all(
    files.filter((file) => !keep.has(file)).map((file) => rm(path.join(lexiconsDir, file))),
  );
  await removeEmptyDirectories(lexiconsDir);

  for (const file of keep) {
    const absolute = path.join(lexiconsDir, file);
    const source = await readFile(absolute, "utf8");
    const directory = path.posix.dirname(file);
    const linked = source.replaceAll(/from "(\.\.?\/[^"]+)"/g, (match, specifier) => {
      // Workaround for bluesky-social/atproto#5738: @atproto/lex 0.4.2 emits
      // "./.defs.js" for a query whose namespace is a record NSID
      // (org.hypercerts.collection.getCollection imports
      // org.hypercerts.collection). Remove once fixed upstream.
      const fixed =
        specifier === "./.defs.js" ? `../${path.posix.basename(directory)}.defs.js` : specifier;
      const target = path.posix.normalize(path.posix.join(directory, fixed));
      if (keep.has(target.replace(/\.js$/, ".ts"))) {
        return fixed === specifier ? match : `from "${fixed}"`;
      }
      const modulePath = target.slice(0, -".js".length);
      if (!existsSync(path.join(lexiconRoot, "dist/records", `${modulePath}.js`))) {
        throw new Error(`${file} needs ${modulePath}, which ${recordsSpecifier} does not export`);
      }
      return `from "${recordsSpecifier}/${modulePath}"`;
    });
    if (linked !== source) await writeFile(absolute, linked);
  }
}

/** @param {string} dir */
async function removeEmptyDirectories(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  for (const entry of entries.filter((entry) => entry.isDirectory())) {
    const child = path.join(dir, entry.name);
    await removeEmptyDirectories(child);
    if ((await readdir(child)).length === 0) await rm(child, { recursive: true });
  }
}

/**
 * Sorts the `export * as x from` lines in lex's namespace modules, so the
 * output does not depend on the order the generator reads files in.
 * @param {string} lexiconsDir
 */
async function sortNamespaceExports(lexiconsDir) {
  for (const file of await listFiles(lexiconsDir)) {
    if (file.endsWith(".defs.ts")) continue;
    const absolute = path.join(lexiconsDir, file);
    const lines = (await readFile(absolute, "utf8")).split("\n");
    const exports = lines.filter((line) => line.startsWith("export * as "));
    if (exports.length < 2) continue;
    const sorted = [...exports].sort(byCodeUnit);
    let next = 0;
    const result = lines.map((line) => (line.startsWith("export * as ") ? sorted[next++] : line));
    await writeFile(absolute, result.join("\n"));
  }
}

/** @param {string} srcDir @param {string} lexiconVersion */
async function writeIndex(srcDir, lexiconVersion) {
  const lines = [
    header,
    "// lex's NSID namespace tree for the Hypercerts API: queries are generated",
    "// here; records and other definitions come from",
    `// ${recordsSpecifier}, so org.hypercerts.claim.activity is the same`,
    "// module in both packages.",
    'export * from "./lexicons/index.js";',
    "",
    "/** Version of @hypercerts-org/lexicon these definitions were generated from. */",
    `export const LEXICON_VERSION = ${JSON.stringify(lexiconVersion)};`,
  ];
  await writeFile(path.join(srcDir, "index.ts"), `${lines.join("\n")}\n`);
}

/** @param {string} srcDir @param {{ root: string; version: string }} lexiconPkg */
async function generate(srcDir, lexiconPkg) {
  if (!existsSync(lexEntry)) {
    throw new Error(`@atproto/lex is not installed at ${lexEntry}; run \`pnpm install\` first.`);
  }
  const lexicons = await manifestLexicons(lexiconPkg.root);
  const lexiconsDir = path.join(srcDir, "lexicons");
  const inputDir = await mkdtemp(path.join(tmpdir(), "hypercerts-api-lexicons-"));
  try {
    await Promise.all(
      lexicons.map(({ id, lexicon }) =>
        writeFile(path.join(inputDir, `${id}.json`), JSON.stringify(lexicon)),
      ),
    );
    execFileSync(
      process.execPath,
      [lexEntry, "build", "--lexicons", inputDir, "--out", lexiconsDir, "--clear", "--index-file"],
      { stdio: ["ignore", "ignore", "inherit"] },
    );
  } finally {
    await rm(inputDir, { recursive: true, force: true });
  }
  const localIds = lexicons.filter((entry) => entry.local).map((entry) => entry.id);
  await linkRecords(lexiconsDir, localIds, lexiconPkg.root);
  await sortNamespaceExports(lexiconsDir);
  await writeIndex(srcDir, lexiconPkg.version);
}

/** @param {string} dir @returns {Promise<Map<string, string>>} index.ts and lexicons/** */
async function readGenerated(dir) {
  const files = (await listFiles(dir)).filter(
    (file) => file === "index.ts" || file.startsWith("lexicons/"),
  );
  const contents = await Promise.all(files.map((file) => readFile(path.join(dir, file), "utf8")));
  return new Map(files.map((file, index) => [file, contents[index] ?? ""]));
}

async function main() {
  const check = process.argv.includes("--check");
  const lexiconPkg = await lexiconPackage();
  const packageFile = path.join(clientRoot, "package.json");
  const packageJson = JSON.parse(await readFile(packageFile, "utf8"));
  const srcDir = path.join(clientRoot, "src");

  if (!check) {
    await generate(srcDir, lexiconPkg);
    packageJson.hypercerts = { ...packageJson.hypercerts, lexiconVersion: lexiconPkg.version };
    await writeFile(packageFile, `${JSON.stringify(packageJson, null, 2)}\n`);
    console.log(
      `Generated @hypercerts-org/api from @hypercerts-org/lexicon ${lexiconPkg.version}.`,
    );
    return;
  }

  const outDir = await mkdtemp(path.join(tmpdir(), "hypercerts-api-src-"));
  try {
    await mkdir(path.join(outDir, "src"));
    await generate(path.join(outDir, "src"), lexiconPkg);
    const expected = await readGenerated(path.join(outDir, "src"));
    const actual = await readGenerated(srcDir);
    const stale = [...new Set([...expected.keys(), ...actual.keys()])]
      .filter((file) => expected.get(file) !== actual.get(file))
      .sort(byCodeUnit);
    if (packageJson.hypercerts?.lexiconVersion !== lexiconPkg.version) {
      stale.unshift("package.json (hypercerts.lexiconVersion)");
    }
    if (stale.length > 0) {
      const list = stale.map((file) => `  ${file}`).join("\n");
      console.error(`Generated sources are stale. Run \`pnpm client:generate\`.\n${list}`);
      process.exitCode = 1;
      return;
    }
    console.log("Generated sources are up to date.");
  } finally {
    await rm(outDir, { recursive: true, force: true });
  }
}

await main();
