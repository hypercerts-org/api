// Generates src/ for @hypercerts-org/api from the Lexicons declared in
// api/manifest.json. Only the API's own Lexicons (api/lexicons/) are kept:
// record types the views embed are imported from
// @hypercerts-org/lexicon/records, not copied. Run with --check to fail when
// the committed output is stale.
import { execFileSync } from "node:child_process";
import { existsSync } from "node:fs";
import { mkdir, mkdtemp, readdir, readFile, rm, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const clientRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const apiRoot = path.resolve(clientRoot, "../api");
const lexEntry = path.join(clientRoot, "node_modules/@atproto/lex/bin/lex");
const recordsSpecifier = "@hypercerts-org/lexicon/records";
const header = "/*\n * THIS FILE WAS GENERATED BY scripts/generate.js. DO NOT EDIT.\n */\n";

// Type names every query module exports; they are reachable through the
// query's namespace export instead of the package root.
const sharedTypeNames = new Set(["Main", "Params", "Input", "Output"]);

// View names that more than one API Lexicon defines, differently. They are
// exported only through their Lexicon's namespace. Generation fails when the
// set changes, because a new entry removes a root export (a breaking change)
// and a removed entry adds one.
const knownAmbiguousTypes = new Set([
  "BadgeDefinitionView",
  "ContributorInformationView",
  "FeatureView",
]);

/** @param {string} a @param {string} b */
const byCodeUnit = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

/** The installed @hypercerts-org/lexicon: its root directory and version. */
async function lexiconPackage() {
  const require = createRequire(path.join(clientRoot, "package.json"));
  const packageFile = require.resolve("@hypercerts-org/lexicon/package.json");
  const { version } = JSON.parse(await readFile(packageFile, "utf8"));
  return { root: path.dirname(packageFile), version: /** @type {string} */ (version) };
}

/**
 * The Lexicons in api/manifest.json validationLexicons: local ones from
 * api/lexicons/, record Lexicons from the installed @hypercerts-org/lexicon.
 * @param {string} lexiconRoot
 * @returns {Promise<Array<{ id: string; local: boolean; lexicon: any }>>}
 */
async function manifestLexicons(lexiconRoot) {
  const manifest = JSON.parse(await readFile(path.join(apiRoot, "manifest.json"), "utf8"));
  return Promise.all(
    manifest.validationLexicons.map(async (/** @type {any} */ source) => {
      const file = source.path
        ? path.join(apiRoot, source.path)
        : path.join(lexiconRoot, source.packagePath);
      const lexicon = JSON.parse(await readFile(file, "utf8"));
      if (lexicon.id !== source.id) {
        throw new Error(
          `api/manifest.json declares ${source.id}, but its source contains ${lexicon.id}`,
        );
      }
      return { id: source.id, local: Boolean(source.path), lexicon };
    }),
  );
}

/** @param {string} id */
const lexiconPath = (id) => id.replaceAll(".", "/");

/** @param {string} dir @returns {Promise<string[]>} paths relative to dir, POSIX separators */
async function listFiles(dir) {
  const entries = await readdir(dir, { recursive: true, withFileTypes: true }).catch(() => []);
  return entries
    .filter((entry) => entry.isFile() && !entry.name.startsWith("."))
    .map((entry) =>
      path.relative(dir, path.join(entry.parentPath, entry.name)).split(path.sep).join("/"),
    )
    .sort(byCodeUnit);
}

/**
 * Keeps only the modules of the API's own Lexicons and points their imports of
 * other Lexicons at @hypercerts-org/lexicon/records.
 * @param {string} lexiconsDir generated output
 * @param {string[]} localIds
 * @param {string} lexiconRoot installed @hypercerts-org/lexicon
 */
async function linkRecords(lexiconsDir, localIds, lexiconRoot) {
  const keep = new Set(
    localIds.flatMap((id) => [`${lexiconPath(id)}.ts`, `${lexiconPath(id)}.defs.ts`]),
  );
  const localDefs = new Set(localIds.map((id) => `${lexiconPath(id)}.defs.js`));
  const files = await listFiles(lexiconsDir);
  await Promise.all(
    files.filter((file) => !keep.has(file)).map((file) => rm(path.join(lexiconsDir, file))),
  );
  await removeEmptyDirectories(lexiconsDir);

  for (const file of files.filter((file) => keep.has(file))) {
    const absolute = path.join(lexiconsDir, file);
    const source = await readFile(absolute, "utf8");
    const directory = path.posix.dirname(file);
    const linked = source.replaceAll(/from "(\.\.?\/[^"]+)"/g, (match, specifier) => {
      // Workaround for bluesky-social/atproto#5738: @atproto/lex 0.4.2 emits
      // "./.defs.js" for a query whose namespace is a record NSID
      // (org.hypercerts.collection.getCollection imports
      // org.hypercerts.collection). Remove once fixed upstream.
      const fixed =
        specifier === "./.defs.js" ? `../${path.posix.basename(directory)}.defs.js` : specifier;
      const target = path.posix.normalize(path.posix.join(directory, fixed));
      if (localDefs.has(target) || !target.endsWith(".defs.js")) {
        return fixed === specifier ? match : `from "${fixed}"`;
      }
      const recordPath = target.slice(0, -".js".length);
      if (!existsSync(path.join(lexiconRoot, "dist/records", `${recordPath}.js`))) {
        throw new Error(
          `${file} imports ${recordPath}, which @hypercerts-org/lexicon/records does not export`,
        );
      }
      return `from "${recordsSpecifier}/${recordPath}"`;
    });
    if (linked !== source) await writeFile(absolute, linked);
  }
}

/** @param {string} dir */
async function removeEmptyDirectories(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  for (const entry of entries.filter((entry) => entry.isDirectory())) {
    const child = path.join(dir, entry.name);
    await removeEmptyDirectories(child);
    if ((await readdir(child)).length === 0) await rm(child, { recursive: true });
  }
}

/** @param {string} id */
const modulePath = (id) => `./lexicons/${lexiconPath(id)}.js`;

/** @param {string} source */
function exportedTypeNames(source) {
  return [...source.matchAll(/^export type \{ (\w+) \};$/gm)]
    .map((match) => /** @type {string} */ (match[1]))
    .filter((name) => !name.startsWith("$") && !sharedTypeNames.has(name));
}

/** @param {string} name */
const capitalize = (name) => name[0]?.toUpperCase() + name.slice(1);

// GetActivity for org.hypercerts.claim.getActivity, ApiDefs for org.hypercerts.api.defs.
/** @param {string} id */
function namespaceName(id) {
  const parts = id.split(".");
  const name = /** @type {string} */ (parts.at(-1));
  return name === "defs"
    ? `${capitalize(/** @type {string} */ (parts.at(-2)))}Defs`
    : capitalize(name);
}

/**
 * Reads the type names each generated Lexicon module exports, and checks the
 * names more than one module exports against knownAmbiguousTypes.
 * @param {string} srcDir
 * @param {string[]} ids
 */
async function collectTypes(srcDir, ids) {
  const sources = await Promise.all(
    ids.map((id) => readFile(path.join(srcDir, `${modulePath(id).slice(2, -3)}.defs.ts`), "utf8")),
  );
  /** @type {Map<string, string[]>} */
  const typesById = new Map(ids.map((id, index) => [id, exportedTypeNames(sources[index] ?? "")]));
  const all = [...typesById.values()].flat();
  // Guards against a change in how lex writes type exports, which would
  // otherwise silently drop every root type export.
  if (all.length === 0) throw new Error("Found no type exports in the generated Lexicon modules");
  const counts = new Map();
  for (const name of all) counts.set(name, (counts.get(name) ?? 0) + 1);
  const ambiguous = [...counts]
    .filter(([, count]) => count > 1)
    .map(([name]) => /** @type {string} */ (name))
    .sort(byCodeUnit);
  const added = ambiguous.filter((name) => !knownAmbiguousTypes.has(name));
  const gone = [...knownAmbiguousTypes].filter((name) => !ambiguous.includes(name));
  if (added.length > 0 || gone.length > 0) {
    throw new Error(
      `View names defined by more than one API Lexicon changed (new: ${added.join(", ") || "none"}; ` +
        `no longer ambiguous: ${gone.join(", ") || "none"}). Update knownAmbiguousTypes in ` +
        "scripts/generate.js; a new entry removes a root export, which is a breaking change.",
    );
  }
  return { typesById, ambiguous };
}

/**
 * Export lines for one Lexicon module: the query definition by its short name
 * (queries only), the module as a namespace, and its unambiguous type names.
 * @param {string} id
 * @param {string | undefined} query
 * @param {string[]} types
 */
function exportLines(id, query, types) {
  const from = JSON.stringify(modulePath(id));
  const lines = [""];
  if (query) lines.push(`export { default as ${query} } from ${from};`);
  lines.push(`export * as ${namespaceName(id)} from ${from};`);
  if (types.length > 0) lines.push(`export type { ${types.join(", ")} } from ${from};`);
  return lines;
}

/**
 * @param {string} srcDir
 * @param {Array<{ id: string; local: boolean; lexicon: any }>} lexicons
 * @param {string} lexiconVersion
 */
async function writeIndex(srcDir, lexicons, lexiconVersion) {
  const local = lexicons.filter((entry) => entry.local).sort((a, b) => byCodeUnit(a.id, b.id));
  const queryIds = local
    .filter((entry) => entry.lexicon.defs?.main?.type === "query")
    .map((entry) => entry.id);
  const defsIds = local
    .filter((entry) => entry.lexicon.defs?.main === undefined)
    .map((entry) => entry.id);
  const ids = [...queryIds, ...defsIds];
  const { typesById, ambiguous } = await collectTypes(srcDir, ids);

  /** @type {Set<string>} */
  const exportNames = new Set();
  const lines = [
    header,
    "// Query definitions for @atproto/lex, one per endpoint, and the types of",
    "// their parameters and views. Each query and defs Lexicon is also exported",
    "// as a namespace (GetActivity.$Params, ApiDefs.ProfileView). Record types",
    `// come from ${recordsSpecifier}.`,
  ];
  if (ambiguous.length > 0) {
    lines.push(
      `// Defined differently by more than one Lexicon, so namespace-only: ${ambiguous.join(", ")}.`,
    );
  }
  lines.push(
    "",
    "/** Version of @hypercerts-org/lexicon these definitions were generated from. */",
    `export const LEXICON_VERSION = ${JSON.stringify(lexiconVersion)};`,
  );
  for (const id of ids) {
    const query = queryIds.includes(id) ? id.split(".").at(-1) : undefined;
    const types = (typesById.get(id) ?? []).filter((name) => !ambiguous.includes(name));
    for (const name of [query, namespaceName(id), ...types].filter((name) => name !== undefined)) {
      if (exportNames.has(name)) throw new Error(`Two API Lexicons export ${name}`);
      exportNames.add(name);
    }
    lines.push(...exportLines(id, query, types));
  }
  await writeFile(path.join(srcDir, "index.ts"), `${lines.join("\n")}\n`);
}

/** @param {string} srcDir @param {{ root: string; version: string }} lexiconPkg */
async function generate(srcDir, lexiconPkg) {
  if (!existsSync(lexEntry)) {
    throw new Error(`@atproto/lex is not installed at ${lexEntry}; run \`pnpm install\` first.`);
  }
  const lexicons = await manifestLexicons(lexiconPkg.root);
  const lexiconsDir = path.join(srcDir, "lexicons");
  const inputDir = await mkdtemp(path.join(tmpdir(), "hypercerts-api-lexicons-"));
  try {
    await Promise.all(
      lexicons.map(({ id, lexicon }) =>
        writeFile(path.join(inputDir, `${id}.json`), JSON.stringify(lexicon)),
      ),
    );
    execFileSync(
      process.execPath,
      [lexEntry, "build", "--lexicons", inputDir, "--out", lexiconsDir, "--clear"],
      { stdio: ["ignore", "ignore", "inherit"] },
    );
  } finally {
    await rm(inputDir, { recursive: true, force: true });
  }
  const localIds = lexicons.filter((entry) => entry.local).map((entry) => entry.id);
  await linkRecords(lexiconsDir, localIds, lexiconPkg.root);
  await writeIndex(srcDir, lexicons, lexiconPkg.version);
}

/** @param {string} dir @returns {Promise<Map<string, string>>} index.ts and lexicons/** */
async function readGenerated(dir) {
  const files = (await listFiles(dir)).filter(
    (file) => file === "index.ts" || file.startsWith("lexicons/"),
  );
  const contents = await Promise.all(files.map((file) => readFile(path.join(dir, file), "utf8")));
  return new Map(files.map((file, index) => [file, contents[index] ?? ""]));
}

async function main() {
  const check = process.argv.includes("--check");
  const lexiconPkg = await lexiconPackage();
  const packageFile = path.join(clientRoot, "package.json");
  const packageJson = JSON.parse(await readFile(packageFile, "utf8"));
  const srcDir = path.join(clientRoot, "src");

  if (!check) {
    await generate(srcDir, lexiconPkg);
    packageJson.hypercerts = { ...packageJson.hypercerts, lexiconVersion: lexiconPkg.version };
    await writeFile(packageFile, `${JSON.stringify(packageJson, null, 2)}\n`);
    console.log(
      `Generated @hypercerts-org/api from @hypercerts-org/lexicon ${lexiconPkg.version}.`,
    );
    return;
  }

  const outDir = await mkdtemp(path.join(tmpdir(), "hypercerts-api-src-"));
  try {
    await mkdir(path.join(outDir, "src"));
    await generate(path.join(outDir, "src"), lexiconPkg);
    const expected = await readGenerated(path.join(outDir, "src"));
    const actual = await readGenerated(srcDir);
    const stale = [...new Set([...expected.keys(), ...actual.keys()])]
      .filter((file) => expected.get(file) !== actual.get(file))
      .sort(byCodeUnit);
    if (packageJson.hypercerts?.lexiconVersion !== lexiconPkg.version) {
      stale.unshift("package.json (hypercerts.lexiconVersion)");
    }
    if (stale.length > 0) {
      const list = stale.map((file) => `  ${file}`).join("\n");
      console.error(`Generated sources are stale. Run \`pnpm client:generate\`.\n${list}`);
      process.exitCode = 1;
      return;
    }
    console.log("Generated sources are up to date.");
  } finally {
    await rm(outDir, { recursive: true, force: true });
  }
}

await main();
