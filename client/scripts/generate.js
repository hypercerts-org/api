// Generates src/ for @hypercerts-org/api from the Lexicons declared in
// api/manifest.json: the API's query Lexicons and the record Lexicons they
// reference, read from the pinned @hypercerts-org/lexicon package through the
// same source reader as the installer. Run with --check to fail when the
// committed output is stale.
import { execFileSync } from "node:child_process";
import { mkdtemp, mkdir, readFile, readdir, rm, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { readLexiconSource } from "../../api/tooling/lexicon-source.js";

const clientRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const apiRoot = path.resolve(clientRoot, "../api");
const lexBin = path.join(clientRoot, "node_modules/.bin/lex");
const header = "/*\n * THIS FILE WAS GENERATED BY scripts/generate.js. DO NOT EDIT.\n */\n";

// Type names every query module exports; they are reachable through the
// query's namespace export instead of the package root.
const sharedTypeNames = new Set(["Main", "Params", "Input", "Output"]);

/** @returns {Promise<string>} */
async function pinnedLexiconVersion() {
  const require = createRequire(path.join(apiRoot, "package.json"));
  const packageFile = require.resolve("@hypercerts-org/lexicon/package.json");
  return JSON.parse(await readFile(packageFile, "utf8")).version;
}

/** @returns {Promise<Array<{ id: string; local: boolean; lexicon: any }>>} */
async function manifestLexicons() {
  const manifest = JSON.parse(await readFile(path.join(apiRoot, "manifest.json"), "utf8"));
  return Promise.all(
    manifest.validationLexicons.map(async (/** @type {any} */ source) => {
      const lexicon = /** @type {any} */ (await readLexiconSource(source, apiRoot));
      if (lexicon.id !== source.id) {
        throw new Error(
          `api/manifest.json declares ${source.id}, but its source contains ${lexicon.id}`,
        );
      }
      return { id: source.id, local: Boolean(source.path), lexicon };
    }),
  );
}

// Workaround for bluesky-social/atproto#5738: @atproto/lex 0.4.2 emits
// `from "./.defs.js"` for a query whose namespace is a record NSID
// (org.hypercerts.collection.getCollection). Remove once fixed upstream.
/** @param {string} dir */
async function fixLexImports(dir) {
  const entries = await readdir(dir, { recursive: true, withFileTypes: true });
  const files = entries.filter((entry) => entry.isFile() && entry.name.endsWith(".ts"));
  await Promise.all(
    files.map(async (entry) => {
      const file = path.join(entry.parentPath, entry.name);
      const source = await readFile(file, "utf8");
      const parent = path.basename(entry.parentPath);
      const fixed = source.replaceAll('from "./.defs.js"', `from "../${parent}.defs.js"`);
      if (fixed !== source) await writeFile(file, fixed);
    }),
  );
}

/** @param {string} id */
const modulePath = (id) => `./lexicons/${id.replaceAll(".", "/")}.js`;

/** @param {string} source */
function exportedTypeNames(source) {
  return [...source.matchAll(/^export type \{ (\w+) \};$/gm)]
    .map((match) => /** @type {string} */ (match[1]))
    .filter((name) => !name.startsWith("$") && !sharedTypeNames.has(name));
}

/** @param {string} name */
const capitalize = (name) => name[0]?.toUpperCase() + name.slice(1);

// GetActivity for org.hypercerts.claim.getActivity, ApiDefs for org.hypercerts.api.defs.
/** @param {string} id */
function namespaceName(id) {
  const parts = id.split(".");
  const name = /** @type {string} */ (parts.at(-1));
  return name === "defs"
    ? `${capitalize(/** @type {string} */ (parts.at(-2)))}Defs`
    : capitalize(name);
}

/** @param {string} a @param {string} b */
const byString = (a, b) => a.localeCompare(b);

/**
 * Reads the type names each generated Lexicon module exports, and the names
 * more than one module exports.
 * @param {string} srcDir
 * @param {string[]} ids
 */
async function collectTypes(srcDir, ids) {
  const sources = await Promise.all(
    ids.map((id) => readFile(path.join(srcDir, `${modulePath(id).slice(2, -3)}.defs.ts`), "utf8")),
  );
  /** @type {Map<string, string[]>} */
  const typesById = new Map(ids.map((id, index) => [id, exportedTypeNames(sources[index] ?? "")]));
  const counts = new Map();
  for (const name of [...typesById.values()].flat()) counts.set(name, (counts.get(name) ?? 0) + 1);
  const ambiguous = [...counts]
    .filter(([, count]) => count > 1)
    .map(([name]) => name)
    .sort(byString);
  return { typesById, ambiguous };
}

/**
 * Export lines for one Lexicon module: the query definition by its short name
 * (queries only), the module as a namespace, and its unambiguous type names.
 * @param {string} id
 * @param {string | undefined} query
 * @param {string[]} types
 */
function exportLines(id, query, types) {
  const from = JSON.stringify(modulePath(id));
  const lines = [""];
  if (query) lines.push(`export { default as ${query} } from ${from};`);
  lines.push(`export * as ${namespaceName(id)} from ${from};`);
  if (types.length > 0) lines.push(`export type { ${types.join(", ")} } from ${from};`);
  return lines;
}

/**
 * @param {string} srcDir
 * @param {Array<{ id: string; local: boolean; lexicon: any }>} lexicons
 * @param {string} lexiconVersion
 */
async function writeIndex(srcDir, lexicons, lexiconVersion) {
  const local = lexicons.filter((entry) => entry.local).sort((a, b) => byString(a.id, b.id));
  const queryIds = local
    .filter((entry) => entry.lexicon.defs?.main?.type === "query")
    .map((entry) => entry.id);
  const defsIds = local
    .filter((entry) => entry.lexicon.defs?.main === undefined)
    .map((entry) => entry.id);
  const ids = [...queryIds, ...defsIds];
  // Some API Lexicons define different views under the same name; those stay
  // reachable only through their Lexicon's namespace.
  const { typesById, ambiguous } = await collectTypes(srcDir, ids);

  /** @type {Set<string>} */
  const exportNames = new Set();
  const lines = [
    header,
    "// Query definitions for @atproto/lex, one per endpoint, and the types of",
    "// their parameters and views. Each query and defs Lexicon is also exported",
    "// as a namespace (GetActivity.$Params, ApiDefs.ProfileView).",
  ];
  if (ambiguous.length > 0) {
    lines.push(
      `// Defined differently by more than one Lexicon, so namespace-only: ${ambiguous.join(", ")}.`,
    );
  }
  lines.push(
    "",
    "/** Version of @hypercerts-org/lexicon these definitions were generated from. */",
    `export const LEXICON_VERSION = ${JSON.stringify(lexiconVersion)};`,
  );
  for (const id of ids) {
    const query = queryIds.includes(id) ? id.split(".").at(-1) : undefined;
    for (const name of [query, namespaceName(id)].filter((name) => name !== undefined)) {
      if (exportNames.has(name)) throw new Error(`Two API Lexicons export ${name}`);
      exportNames.add(name);
    }
    const types = (typesById.get(id) ?? []).filter((name) => !ambiguous.includes(name));
    lines.push(...exportLines(id, query, types));
  }
  await writeFile(path.join(srcDir, "index.ts"), `${lines.join("\n")}\n`);
}

/** @param {string} srcDir @param {string} lexiconVersion */
async function generate(srcDir, lexiconVersion) {
  const lexicons = await manifestLexicons();
  const inputDir = await mkdtemp(path.join(tmpdir(), "hypercerts-api-lexicons-"));
  try {
    await Promise.all(
      lexicons.map(({ id, lexicon }) =>
        writeFile(path.join(inputDir, `${id}.json`), JSON.stringify(lexicon)),
      ),
    );
    execFileSync(
      lexBin,
      ["build", "--lexicons", inputDir, "--out", path.join(srcDir, "lexicons"), "--clear"],
      {
        stdio: ["ignore", "ignore", "inherit"],
      },
    );
  } finally {
    await rm(inputDir, { recursive: true, force: true });
  }
  await fixLexImports(path.join(srcDir, "lexicons"));
  await writeIndex(srcDir, lexicons, lexiconVersion);
}

/** @param {string} dir @returns {Promise<Map<string, string>>} */
async function readTree(dir) {
  const entries = await readdir(dir, { recursive: true, withFileTypes: true }).catch(() => []);
  const files = entries
    .filter((entry) => entry.isFile())
    .map((entry) => path.join(entry.parentPath, entry.name));
  const contents = await Promise.all(files.map((file) => readFile(file, "utf8")));
  return new Map(files.map((file, index) => [path.relative(dir, file), contents[index] ?? ""]));
}

async function main() {
  const check = process.argv.includes("--check");
  const lexiconVersion = await pinnedLexiconVersion();
  const packageFile = path.join(clientRoot, "package.json");
  const packageJson = JSON.parse(await readFile(packageFile, "utf8"));
  const srcDir = path.join(clientRoot, "src");

  if (!check) {
    await generate(srcDir, lexiconVersion);
    packageJson.hypercerts = { ...packageJson.hypercerts, lexiconVersion };
    await writeFile(packageFile, `${JSON.stringify(packageJson, null, 2)}\n`);
    console.log(`Generated @hypercerts-org/api from @hypercerts-org/lexicon ${lexiconVersion}.`);
    return;
  }

  const outDir = await mkdtemp(path.join(tmpdir(), "hypercerts-api-src-"));
  try {
    await mkdir(path.join(outDir, "src"));
    await generate(path.join(outDir, "src"), lexiconVersion);
    const expected = await readTree(path.join(outDir, "src"));
    const actual = await readTree(srcDir);
    const stale = [...new Set([...expected.keys(), ...actual.keys()])]
      .filter((file) => expected.get(file) !== actual.get(file))
      .sort(byString);
    if (packageJson.hypercerts?.lexiconVersion !== lexiconVersion)
      stale.unshift("package.json (hypercerts.lexiconVersion)");
    if (stale.length > 0) {
      const list = stale.map((file) => `  ${file}`).join("\n");
      console.error(
        `Generated sources are stale. Run \`pnpm --filter @hypercerts-org/api generate\`.\n${list}`,
      );
      process.exitCode = 1;
      return;
    }
    console.log("Generated sources are up to date.");
  } finally {
    await rm(outDir, { recursive: true, force: true });
  }
}

await main();
